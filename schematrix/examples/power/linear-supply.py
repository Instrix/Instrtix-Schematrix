# Mains to 5 V: transformer, bridge rectifier, reservoir capacitor and a 7805 regulator.
from schematrix import Schematic

s = Schematic('Linear power supply', description='230 V AC to regulated 5 V, 1 A')
s.terminal((40, 50), 'L'); s.terminal((40, 110), 'N')
f1 = s.fuse(anchor='1', at=(60, 50), length=40, value='500 mA T', ref='F1')
t1 = s.transformer(anchor='P1', at=(130, 50), ref='T1', value='230 V : 9 V')
s.wire((40, 50), f1['1']); s.wire(f1['2'], t1['P1'])
s.wire((40, 110), t1['P2'])
br = s.bridge(anchor='AC1', at=(230, 80), ref='D1', part='DF04')
s.wire(t1['S1'], (210, 50), (210, 80), br['AC1'])
s.wire(t1['S2'], (210, 110), (330, 110), (330, 80), br['AC2'])
s.wire(br['+'], (270, 25), (380, 25))
s.gnd(br['-'])
c1 = s.electrolytic(anchor='1', at=(380, 25), rot=90, value='2200 \\uF', ref='C1', fields={'Voltage rating': ('25 V', True)})
s.gnd(c1['2'])
u = s.regulator(anchor='IN', at=(430, 25), ref='U1', part='LM7805')
s.wire((380, 25), u['IN'])
s.gnd(u['GND'])
c2 = s.capacitor(anchor='1', at=(540, 25), rot=90, value='100 nF', ref='C2')
s.wire(u['OUT'], (540, 25))
s.gnd(c2['2'])
s.rail(s.wire((540, 25), (590, 25), (590, 5))[-1], '+5 V')
s.note(40, 190, 'V_{in(reg)} \\approx 9 V \\times \\sqrt{}2 \\- 2 V_{F} \\approx 11 V;  ripple \\approx I / (2 f C) \\approx 4.5 V_{pp} at 1 A')
s.show()
