# Common-emitter BJT amplifier with emitter degeneration, gain ~ -R3/R4. Simulates with the default NPN model.
from schematrix import Schematic

s = Schematic('Common-emitter amplifier', description='Voltage-divider bias, gain about -4.7')
q = s.npn((240, 170), ref='Q1')                                 # C (240, 140), B (210, 170), E (240, 200)
s.rail((160, 40), '+12 V')
s.wire((160, 40), (240, 40))
r1 = s.resistor(anchor='1', at=(160, 40), rot=90, value='47 k\\ohm', ref='R1')
r2 = s.resistor(anchor='1', at=(160, 170), rot=90, value='10 k\\ohm', ref='R2')
s.wire(r1['2'], r2['1']); s.wire((160, 170), q['B'])
s.gnd(r2['2'])
r3 = s.resistor(anchor='1', at=(240, 40), rot=90, value='4.7 k\\ohm', ref='R3')
s.wire(r3['2'], q['C'])
r4 = s.resistor(anchor='1', at=q['E'], rot=90, value='1 k\\ohm', ref='R4')
s.gnd(r4['2'])
c2 = s.capacitor(anchor='1', at=(300, 120), value='1 \\uF', ref='C2')
s.wire((240, 120), c2['1'])
s.flag(s.wire(c2['2'], (370, 120))[-1], 'OUT', side='right')
c1 = s.capacitor(anchor='2', at=(140, 170), value='1 \\uF', ref='C1')
s.wire(c1['2'], (160, 170))
v1 = s.vsrc(anchor='p', at=(50, 190), rot=90, length=80, kind='ac', value='SIN(0 20m 1k)', ref='V1', label_offset=(-150, 0))
s.wire(v1['p'], (50, 170), c1['1'])
s.gnd(v1['n'])
v2 = s.vsrc(anchor='p', at=(460, 60), rot=90, length=80, value='12', ref='V2')
s.rail(v2['p'], '+12 V'); s.gnd(v2['n'])
s.directive('.tran 10u 4m')
s.show()
