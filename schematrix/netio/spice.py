def _defined(directives, name) -> bool:
    pat = re.compile(rf'^\s*\.(model|subckt)\s+{re.escape(name)}\b', re.I | re.M)
    return any(pat.search(d) for d in directives)


def export(nl: Netlist, title=None) -> str:
    lines = [f'* {title or nl.title or "Schematrix netlist"}', '* generated by Schematrix']
    lines += [f'* warning: {w}' for w in nl.warnings]
    renamed = {net_name(n): n for n in nl.nets() if net_name(n) != n}
    if renamed:
        lines.append('*@nets ' + json.dumps(renamed, ensure_ascii=False))
    for p in nl.parts:
        meta = {'ref': p.ref, 'sym': p.sym}
        if p.props:
            meta['props'] = p.props
        if p.fields:
            meta['fields'] = p.fields
        if p.part:
            meta['part'] = p.part
        if p.value:
            meta['value'] = p.value
        lines.append('*@ ' + json.dumps(meta, ensure_ascii=False))
        ln = line(p)
        lines.append(ln if ln else f'* {p.ref}: {p.symbol.title if p.symbol else p.sym} (no SPICE model) '
                     + ' '.join(f'{k}={net_name(v)}' for k, v in p.pins.items()))
    used = []
    for p in nl.parts:
        if p.symbol and p.symbol.spice and '{model}' in p.symbol.spice:
            m = FIELDS['model'](p.symbol, p.all_props())
            if m in DEFAULT_MODELS and m not in used and not _defined(nl.directives, m):
                used.append(m)
    if used:
        lines.append('* default models')
        lines += [DEFAULT_MODELS[m] for m in used]
    if nl.directives:
        lines.append('* directives')
        lines += [d for d in nl.directives if d.strip().lower() not in ('.end', '.end.')]
        low = [d.strip().lower() for d in nl.directives]
        if any(d.startswith('.ac') for d in low) and not any(d.startswith('.save') for d in low):
            lines.append('.save all')             # ngspice batch runs keep no .ac vectors otherwise
    lines.append('.end')
    return '\n'.join(lines) + '\n'


# ---------------------------------------------------------------- reading
NODES = {'R': 2, 'C': 2, 'L': 2, 'D': 2, 'V': 2, 'I': 2, 'B': 2, 'Q': 3, 'J': 3, 'M': 4, 'E': 4, 'G': 4, 'H': 2, 'F': 2,
         'S': 4, 'W': 2, 'T': 4, 'K': 0}
BY_LETTER = {'R': 'resistor', 'C': 'capacitor', 'L': 'inductor', 'D': 'diode', 'V': 'vsrc', 'I': 'isrc', 'Q': 'npn',
             'M': 'nmos', 'J': 'njfet', 'E': 'vcvs', 'G': 'vccs', 'H': 'ccvs', 'F': 'cccs'}


def _logical_lines(text):
    out = []
    for raw in text.splitlines():
        s = raw.rstrip()
        if s.startswith('+') and out:
            out[-1] += ' ' + s[1:].strip()
        else:
            out.append(s)
    return out


def _resolve(letter, nodes, tail, warnings, ref, models):
    """-> (symbol name, props, value, part) for a foreign SPICE element; models: .model name -> type"""
    model = tail[0] if tail else ''
    M = (models.get(model.upper(), '') + ' ' + model).upper()
    if letter in ('R', 'C', 'L'):
        return BY_LETTER[letter], {}, ' '.join(tail[:1]), ''
    if letter == 'D':
        kind = 'led' if 'LED' in M else 'zener' if M.startswith(('DZ', 'BZ', 'ZEN')) or 'ZENER' in M else \
            'schottky' if 'SCHOTT' in M or M.startswith(('BAT', 'SS1', '1N58')) else 'standard'
        return 'diode', ({'kind': kind} if kind != 'standard' else {}), '', model
    if letter == 'Q':
        return ('pnp' if 'PNP' in M else 'npn'), {}, '', model
    if letter == 'M':
        sym = 'pmos' if M.startswith('P') or 'PMOS' in M or 'PCH' in M else 'nmos'
        return sym, {}, '', model
    if letter == 'J':
        return ('pjfet' if M.startswith('P') else 'njfet'), {}, '', model
    if letter in ('V', 'I'):
        val = ' '.join(tail)
        kind = 'dc'
        u = val.upper()
        if u.startswith('DC '):
            val = val[3:].strip()
        elif u.startswith('AC ') or u.startswith('SIN'):
            kind = 'ac'; val = val[3:].strip() if u.startswith('AC ') else val
        elif u.startswith('PULSE'):
            kind = 'pulse'
        return BY_LETTER[letter], ({'kind': kind} if kind != 'dc' and letter == 'V' else {}), val, ''
    if letter in ('E', 'G'):
        return BY_LETTER[letter], {}, ' '.join(tail[:1]), ''
    if letter in ('H', 'F'):
        return BY_LETTER[letter], {'control': tail[0] if tail else 'V1'}, ' '.join(tail[1:2]), ''
    warnings.append(f'{ref}: SPICE element type {letter} drawn as a generic block')
    return None, {}, '', model


def parse(text: str) -> Netlist:
    lines = _logical_lines(text)
    nl = Netlist()
    if lines:
        nl.title = lines[0].lstrip('*').strip()
        lines = lines[1:]
    meta: dict = {}
    renamed: dict = {}
    models = {m.group(1).upper(): m.group(2).upper() for m in
              (re.match(r'^\.model\s+(\S+)\s+(.+)$', x.strip(), re.I) for x in lines) if m}
    sub = 0
    for s in lines:
        st = s.strip()
        if not st:
            continue
        if st.startswith('*@nets'):
            try:
                renamed.update(json.loads(st[6:]))
            except ValueError:
                pass
            continue
        if st.startswith('*@'):
            try:
                m = json.loads(st[2:]); meta[str(m.get('ref'))] = m
            except ValueError:
                pass
            continue
        if st.startswith('*'):
            continue
        st = re.split(r'\s;|\$ ', st)[0].strip()
        low = st.lower()
        if low.startswith('.subckt'):
            sub += 1; nl.directives.append(st); continue
        if low.startswith('.ends'):
            sub = max(0, sub - 1); nl.directives.append(st); continue
        if sub:
            nl.directives.append(st); continue
        if sub or st.startswith('.'):
            if not st.lower().startswith(('.end', '.title')):
                nl.directives.append(st)          # analyses, options, models: kept with the imported sheet
            continue
        toks = re.sub(r'\(\s*', '(', st).split()
        name, letter = toks[0], toks[0][0].upper()
        args = toks[1:]
        if letter == 'X':
            nodes, tail = args[:-1], args[-1:]
        else:
            n = NODES.get(letter, 2)
            nodes, tail = args[:n], args[n:]
        ref = name
        m = meta.get(name) or next((v for k, v in meta.items() if spice_name(letter, k) == name), None)
        if m:
            ref = m['ref']
        nodes = [renamed.get(n, n) for n in nodes]
        part = _part(letter, ref, nodes, tail, m, nl.warnings, models)
        if part:
            nl.parts.append(part)
    defaults = {re.sub(r'\s+', ' ', x.split('\n')[0]).lower() for x in DEFAULT_MODELS.values()}
    out, skip = [], False
    for d in nl.directives:                      # strip our own default models, keep everything else
        first = re.sub(r'\s+', ' ', d).lower()
        if first in defaults and first.startswith('.subckt'):
            skip = True
        if not skip and first not in defaults:
            out.append(d)
        if skip and first.startswith('.ends'):
            skip = False
    nl.directives = out
    # elements whose SPICE line was only a comment (no model) still carry their pins in the metadata comment
    for raw in lines:
        st = raw.strip()
        mm = re.match(r'^\*\s+(\S+):.*\(no SPICE model\)\s*(.*)$', st)
        if mm and mm.group(1) in meta and not any(p.ref == mm.group(1) for p in nl.parts):
            m = meta[mm.group(1)]
            pins = {k: renamed.get(v, v) for k, v in (kv.split('=', 1) for kv in mm.group(2).split() if '=' in kv)}
            nl.parts.append(Part(m['ref'], m.get('sym'), m.get('value', ''), m.get('part', ''), m.get('props', {}),
                                 m.get('fields', {}), pins, 'spice'))
    return nl


def _part(letter, ref, nodes, tail, meta, warnings, models) -> Part | None:
    if letter == 'K':
        warnings.append(f'{ref}: inductor coupling ignored')
        return None
    if meta and meta.get('sym') in SYM.REGISTRY:
        sym = SYM.get(meta['sym'])
        props = dict(meta.get('props', {}))
        names = sym.pin_names(props)
        pins = _assign(sym, props, names, nodes)
        return Part(ref, sym.name, meta.get('value', ''), meta.get('part', ''), props, meta.get('fields', {}), pins, 'spice')
    if letter == 'X':
        model = tail[0] if tail else 'SUB'
        if model.upper() in ('OPAMP', 'OPAMP1') or re.match(r'^(LM|TL|OP|AD8|OPA|MCP6)\d', model.upper()):
            if len(nodes) in (3, 5):
                props = {'supply': len(nodes) == 5}
                names = ['inp', 'inm', 'vp', 'vn', 'out'] if len(nodes) == 5 else ['inp', 'inm', 'out']
                return Part(ref, 'opamp', '', model, {k: v for k, v in props.items() if v}, {}, dict(zip(names, nodes)), model)
        return _block(ref, model, nodes)
    symname, props, value, part = _resolve(letter, nodes, tail, warnings, ref, models)
    if not symname:
        return _block(ref, part or letter, nodes)
    sym = SYM.get(symname)
    if symname in ('nmos', 'pmos') and len(nodes) == 4 and nodes[3] != nodes[2]:
        props['bulk'] = True
    pins = _assign(sym, props, sym.pin_names(props), nodes)
    if part.upper() == str(sym.model or '').upper():
        part = ''
    return Part(ref, symname, value, part, props, {}, pins, letter)


def _assign(sym, props, names, nodes) -> dict:
    """map positional SPICE nodes onto a symbol's pins via its template"""
    order = template_pins(sym.spice or 'X {*}', names) if sym.spice else [((n,), False) for n in names]
    present = [(alts, opt) for alts, opt in order if any(a in names for a in alts)]
    if len(present) > len(nodes):                                  # drop optional pins first
        present = [x for x in present if not x[1]]
    pins = {}
    for (alts, _), net in zip(present, nodes):
        name = next(a for a in alts if a in names)
        pins.setdefault(name, net)
    return pins


def _block(ref, title, nodes) -> Part:
    n = len(nodes)
    names = [str(i + 1) for i in range(n)]
    spec = ', '.join(f'{nm}:{"l" if i < (n + 1) // 2 else "r"}' for i, nm in enumerate(names))
    h = max(40, 20 * ((n + 1) // 2) + 10)
    return Part(ref, 'block', '', '', {'title': title, 'pins': spec, 'w': 100, 'h': h}, {}, dict(zip(names, nodes)), title)
