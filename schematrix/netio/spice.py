"""SPICE netlists.

Writing: each symbol carries a line template such as 'R {1} {2} {value}' or 'M {D} {G} {S} {B|S} {model}':
    {pin}       the net on that pin            {a|b}   pin a if the symbol has it, else pin b
    {pin?}      the net, or nothing if absent  {*}     every pin, in the symbol's pin order
    {value} {model} {src} {ctrl}               see FIELDS below
Anything else is copied literally. The first letter is the SPICE element type; the reference follows it.

Each part is preceded by a '*@ {json}' comment holding its symbol, properties and fields, so a netlist written
here reads back without loss; other SPICE files are mapped by element letter and model name.
"""
from __future__ import annotations

import json
import re

from .. import symbols as SYM
from ..units import is_number, spice_value
from .model import Netlist, Part

TOKEN = re.compile(r'\{([^{}]+)\}')


def _src(sym, props):
    v = spice_value(props.get('value', ''))
    if v == '?':
        v = '0'
    if is_number(v):
        return ('DC ' if props.get('kind', 'dc') == 'dc' else 'AC ') + v
    return str(props.get('value', '')).strip()


FIELDS = {
    'value': lambda sym, props: spice_value(props.get('value', '')),
    'model': lambda sym, props: re.sub(r'\W', '_', sym.model_name(props)).upper(),
    'src': _src,
    'ctrl': lambda sym, props: spice_name('V', props.get('control') or 'V1'),
}


def net_name(net) -> str:
    """a node name SPICE can read: no spaces, parentheses, commas or '='"""
    from ..markup import plain
    return re.sub(r'[\s(),=;{}]+', '_', plain(str(net))) or '?'


def spice_name(letter, ref):
    ref = re.sub(r'[^A-Za-z0-9_]', '_', str(ref))
    return ref if ref.upper().startswith(letter) else f'{letter}{ref}'


def template_pins(template: str, pin_names) -> list:
    """the pin tokens of a template in order: [(alternatives, optional)]"""
    out = []
    for t in TOKEN.findall(template):
        if t in FIELDS:
            continue
        if t == '*':
            out += [((n,), False) for n in pin_names]
            continue
        out.append((tuple(t.rstrip('?').split('|')), t.endswith('?')))
    return out


def line(part: Part) -> str | None:
    sym = part.symbol
    if not sym or not sym.spice:
        return None
    props = part.all_props()
    names = sym.pin_names(props)
    node = lambda n: net_name(part.pins.get(n, '?'))

    def sub(m):
        t = m.group(1)
        if t in FIELDS:
            return FIELDS[t](sym, props)
        if t == '*':
            return ' '.join(node(n) for n in names)
        for alt in t.rstrip('?').split('|'):
            if alt in names:
                return node(alt)
        return '' if t.endswith('?') else '?'
    letter, _, rest = sym.spice.partition(' ')
    return re.sub(r'\s+', ' ', f'{spice_name(letter, part.ref)} {TOKEN.sub(sub, rest)}').strip()


