"""Connectivity: which pins share a net, net names from labels/terminals/rails/ground, and SPICE export."""
from __future__ import annotations

import re

from . import geometry as GEO
from . import symbols as SYM


class UF:
    def __init__(self):
        self.p = {}

    def find(self, a):
        self.p.setdefault(a, a)
        while self.p[a] != a:
            self.p[a] = self.p[self.p[a]]
            a = self.p[a]
        return a

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.p[rb] = ra


def extract(doc) -> dict:
    """{'nets': {name: [(ref, pin), ...]}, 'pins': {(comp id, pin): net}, 'warnings': [...]}"""
    wires, pts = GEO.connection_points(doc)
    uf = UF()
    K = GEO._key
    for p, src in pts:
        uf.find(K(p))
    for w in wires:
        P = w['points']
        for a, b in zip(P, P[1:]):
            uf.union(K(a), K(b))
            for p, _ in pts:
                if GEO.on_segment(p, a, b):
                    uf.union(K(a), K(p))
    comps = {e['id']: e for e in doc['elements'] if e['type'] == 'comp'}
    names: dict = {}
    warnings = []
    for e in comps.values():
        sym = SYM.get(e['sym'])
        if not sym.net_prop:
            continue
        props = {**sym.defaults(), **e.get('props', {})}
        name = str(props.get(sym.net_prop) or (props.get('label') if e['sym'] == 'terminal' else '') or '').strip()
        if not name:
            continue
        for p in GEO.pins(e).values():
            root = uf.find(K(p))
            if root in names and names[root] != name:
                warnings.append(f'net named both {names[root]!r} and {name!r}')
                continue
            names[root] = name
    # identical names join nets that are not wired together (net labels)
    by_name: dict = {}
    for root, name in list(names.items()):
        if name in by_name:
            uf.union(by_name[name], root)
        else:
            by_name[name] = root
    names = {uf.find(r): n for r, n in names.items()}
    pin_net = {}
    nets: dict = {}
    auto = 0
    autonames: dict = {}
    for e in sorted(comps.values(), key=lambda e: str(e.get('props', {}).get('ref') or e['id'])):
        sym = SYM.get(e['sym'])
        if sym.net_prop or e['sym'] == 'dot':
            continue
        ref = e.get('props', {}).get('ref') or e['id']
        for pin, p in GEO.pins(e).items():
            root = uf.find(K(p))
            if root in names:
                net = names[root]
            else:
                if root not in autonames:
                    auto += 1
                    autonames[root] = f'N{auto:03d}'
                net = autonames[root]
            pin_net[(e['id'], pin)] = net
            nets.setdefault(net, []).append((ref, pin))
    unconnected = [f'{m[0][0]}.{m[0][1]}' for n, m in nets.items() if len(m) == 1 and n.startswith('N')]
    if unconnected:
        warnings.append('unconnected pins: ' + ', '.join(unconnected[:20]) + (' …' if len(unconnected) > 20 else ''))
    return {'nets': nets, 'pins': pin_net, 'warnings': warnings}


_SI = {'f': 'f', 'p': 'p', 'n': 'n', 'u': 'u', 'µ': 'u', 'μ': 'u', 'm': 'm', 'k': 'k', 'K': 'k', 'M': 'Meg', 'G': 'G', 'T': 'T'}


def spice_value(v: str) -> str:
    """'1 kΩ' -> '1k', '10 mΩ' -> '10m', '4.7 µF' -> '4.7u', '2.2 MΩ' -> '2.2Meg', '30.1k' -> '30.1k'"""
    s = str(v or '').strip()
    m = re.match(r'^([-+]?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?)\s*([fpnuµμmkKMGT]?)\s*(Ω|ohm|F|H|V|A|Hz|s)?$', s)
    if not m:
        return s.replace(' ', '') or '?'
    n, pre, unit = m.groups()
    return n + _SI.get(pre, '') if pre else n


def spice_name(letter, ref):
    ref = re.sub(r'[^A-Za-z0-9_]', '_', str(ref))
    return ref if ref.upper().startswith(letter) else f'{letter}{ref}'


def to_spice(doc, title=None) -> str:
    nx = extract(doc)
    pn = nx['pins']
    lines = [f'* {title or doc.get("meta", {}).get("title") or "Schematrix netlist"}', '* generated by Schematrix']
    for w in nx['warnings']:
        lines.append(f'* warning: {w}')
    models = set()
    for e in doc['elements']:
        if e['type'] != 'comp':
            continue
        sym = SYM.get(e['sym'])
        if not sym.spice:
            if not sym.net_prop and e['sym'] != 'dot':
                lines.append(f'* {e.get("props", {}).get("ref") or e["id"]}: {sym.title} (no SPICE model)')
            continue
        props = {**sym.defaults(), **e.get('props', {})}
        ref = props.get('ref') or e['id']
        n = lambda pin: pn.get((e['id'], pin), '?')
        val = spice_value(props.get('value', ''))
        L = sym.spice
        if L in ('R', 'C', 'L'):
            lines.append(f'{spice_name(L, ref)} {n("1")} {n("2")} {val}')
            if e['sym'] == 'potentiometer':
                lines[-1] = f'* {ref}: potentiometer, wiper {n("W")}'
        elif L == 'D':
            mdl = props.get('part') or 'DMOD'; models.add(('D', mdl))
            lines.append(f'{spice_name("D", ref)} {n("A")} {n("K")} {mdl}')
        elif L == 'M':
            mdl = props.get('part') or ('NMOS' if e['sym'] == 'nmos' else 'PMOS')
            lines.append(f'{spice_name("M", ref)} {n("D")} {n("G")} {n("S")} {n("S")} {mdl}')
        elif L == 'Q':
            mdl = props.get('part') or e['sym'].upper()
            lines.append(f'{spice_name("Q", ref)} {n("C")} {n("B")} {n("E")} {mdl}')
        elif L == 'V' or L == 'I':
            v = val if val != '?' else '0'
            if re.match(r'^[-+]?\d', v):
                v = ('DC ' if props.get('kind', 'dc') == 'dc' else 'AC ') + v
            lines.append(f'{spice_name(L, ref)} {n("p")} {n("n")} {v}')
        elif L == 'X':
            g = GEO.geometry(e)
            order = [p for p in ('inp', 'inm', 'vp', 'vn', 'out') if p in g['pins']] if e['sym'] == 'opamp' else list(g['pins'])
            if not order:
                continue
            sub = re.sub(r'\W', '_', str(props.get('part') or props.get('title') or e['sym']).upper())
            lines.append(f'{spice_name("X", ref)} {" ".join(n(p) for p in order)} {sub}')
    lines.append('.end')
    return '\n'.join(lines) + '\n'
